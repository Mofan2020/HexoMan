def available_languages() -> list[dict[str, str]]:
    """语言档列表，界面右上角的切换器用。"""
    return [dict(item) for item in LANGUAGES]


def get_strings(language: str) -> dict[str, str]:
    """取某个语言的文案字典。

    未知语言回落到默认语言，再回落到英文。**不回落成空字典**——
    界面会出现一屏 key 原文，比语言不对更糟。
    """
    if language in STRINGS:
        return dict(STRINGS[language])
    if DEFAULT_LANGUAGE in STRINGS:
        return dict(STRINGS[DEFAULT_LANGUAGE])
    return dict(next(iter(STRINGS.values())))


def t(key: str, language: str = DEFAULT_LANGUAGE, **kwargs: Any) -> str:
    """查一条文案并做占位符替换。

    占位符用 ``{name}`` 形式，和 Python 的 ``str.format`` 一致。
    """
    template = get_strings(language).get(key, key)
    if not kwargs:
        return template
    try:
        return template.format(**kwargs)
    except (KeyError, IndexError):
        return template
